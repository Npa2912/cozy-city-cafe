export function frontageBounds(p) {
  // All planned frontages use quarter-turn rotations.
  const sign = Math.sign(p.rotation);
  return {
    minX: sign > 0 ? p.x - p.d : p.x,
    maxX: sign > 0 ? p.x : p.x + p.d,
    minZ: p.z - p.w / 2,
    maxZ: p.z + p.w / 2,
  };
}
